function c = defaults(project_root)
%DEFAULTS Default ProjectConfig, mirroring the dataclasses in src/panama_uav/config.py.
%   C = panama_uav.config.defaults(PROJECT_ROOT) returns a struct with the
%   sections map, reward, training, curriculum (struct array), uav,
%   communication and evaluation. All numbers are double; Python tuples are
%   row vectors (numbers) or cell rows of char (strings); None is [].
    if nargin < 1
        project_root = '';
    end
    c.project_root = project_root;
    c.map = struct('fov_radius', 7, 'astar_waypoints', 5, 'communicated_path_steps', 5, ...
        'communication_range_factor', 2.0, 'meters_per_cell', 1.0);
    c.reward = struct('goal', 2.0, 'time_step', -0.01, 'collision_agent', -1.0, ...
        'collision_obstacle', -1.0, 'distance_improvement', 0.23, 'path_conflict', -1.0, ...
        'hold', 0.05, 'active_yield', 0.0);
    c.training = struct('target_environment_steps', 80000000, 'gamma', 0.99, 'tau', 0.005, ...
        'learning_rate', 1e-4, 'batch_size', 64, 'replay_capacity', 2000000, ...
        'epsilon_start', 1.0, 'epsilon_end', 0.1, 'epsilon_decay_steps', 5000000, ...
        'per_alpha', 0.6, 'per_beta_start', 0.4, 'per_beta_steps', 60000000, ...
        'per_epsilon', 1e-5, 'model_broadcast_steps', 16, 'checkpoint_interval_steps', 10000, ...
        'validation_interval_episodes', 250, 'validation_episodes', 200, ...
        'budget_seconds', 10800.0, 'shutdown_reserve_seconds', 60.0);
    stages = struct('name', {}, 'map_path', {}, 'num_agents', {}, 'max_episode_steps', {}, ...
        'min_episodes', {}, 'max_episodes', {}, 'graduation_success_rate', {});
    for n = [2 4 6 8]
        stages(end + 1) = panama_uav.config.stage(struct('name', sprintf('agents-%d', n), ...
            'num_agents', n)); %#ok<AGROW>
    end
    c.curriculum = stages;
    c.uav = struct('environment', 'urban', 'carrier_frequency_hz', 2.5e9, ...
        'max_path_loss_db', 85.0, 'speed_m_per_step', 1.0, 'minimum_altitude_m', 20.0, ...
        'blackout_threshold_db', -8.47);
    c.communication = panama_uav.config.transport_defaults();
    c.evaluation = struct('agent_counts', [2 4 6 8], 'cases_per_count', 50, ...
        'delay_steps', [1 2 5 10 20], 'bootstrap_samples', 2000);
end
